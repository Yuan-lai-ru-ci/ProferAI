import type { Channel, ChatSendInput, ChatMessage, ConversationMeta, FileAttachment, KnowledgeReference, KnowledgeSearchResult } from '@profer/shared'
import type { ToolCall, ToolResult, ToolDefinition } from './providers/index.ts'

export interface AutoTitleConversationInput { conversationId: string; channelId: string; modelId: string }
interface AuthSession { baseUrl: string; token: string; proxyToken?: string }
interface TitleWindowInput {
  title: string; defaultTitle: string; titleAutoGeneratedAt?: number; titleRefineAttempts?: number; titleLockedAt?: number; sourceCount: number
}
type TitleDecision = { action: 'lock'; reason: string } | { action: 'skip'; reason: string } | { action: 'generate'; attempts: number; lockAfterApply: boolean }
export interface ChatRuntimePorts {
  emit(conversationId: string, channel: string, payload: unknown): void
  routePluginModel(key: string, input: ChatSendInput): ChatSendInput
  listChannels(): Channel[]
  decryptApiKey(channelId: string): string
  readAttachmentAsBase64(path: string): string
  isImageAttachment(mediaType: string): boolean
  isDocumentAttachment(mediaType: string): boolean
  extractTextFromAttachment(path: string): Promise<string>
  getEffectiveProxyUrl(): Promise<string | undefined>
  getFetchFn(proxyUrl?: string): typeof globalThis.fetch
  getEnabledTools(ids?: string[]): { tools: ToolDefinition[] | undefined; systemPromptAppend?: string }
  executeToolCalls(calls: ToolCall[], context: {
    conversationId: string; runId: string; currentAttachments?: FileAttachment[]; previousUserAttachments?: FileAttachment[]; previousAssistantAttachments?: FileAttachment[]
  }): Promise<ToolResult[]>
  editionProviders: {
    credentials: { shouldUseManagedRoute(channel: Channel, options: { respectDirectDataPlane: boolean }): boolean; managedPath(kind: 'messages' | 'chat'): string }
    account: { getSession(): Promise<AuthSession | null>; recoverSession(): Promise<AuthSession | null> }
    errors: { detectInsufficientCredits(error: unknown): { message: string } | null }
  }
  syncRecoveredChannels(baseUrl: string, token: string): Promise<void>
  resolveEditionBearerToken(session: AuthSession): string
  searchKnowledgeItemsForChat(query: string, ids: string[], topK: number): Promise<KnowledgeSearchResult[]>
  prepareChatKnowledgeRequest(input: { userMessage: string; attachments?: FileAttachment[]; history: ChatMessage[]; currentReferences?: KnowledgeReference[] }, deps: {
    enrichMessage(message: string, attachments?: FileAttachment[]): Promise<string>
    search(query: string, ids: string[], options: { topK: number; maxChars: number }): Promise<KnowledgeSearchResult[]>
  }): Promise<{ providerUserMessage: string; effectiveReferences: KnowledgeReference[]; knowledgeContextChars: number }>
  normalizeChatStreamError(provider: string, error: unknown): { message: string; code?: string; errorTitle?: string }
  conversations: {
    DEFAULT_CONVERSATION_TITLE: string
    appendBranchTail(id: string, message: Omit<ChatMessage, 'id' | 'parentId' | 'createdAt'> & { id?: string; parentId?: string | null; createdAt?: number }): ChatMessage
    getConversationBranch(id: string): ChatMessage[]
    getConversationMeta(id: string): ConversationMeta | null | undefined
    updateConversationMeta(id: string, updates: Partial<Pick<ConversationMeta, 'title' | 'titleAutoGeneratedAt' | 'titleRefineAttempts' | 'titleLockedAt'>>): ConversationMeta
  }
  titlePolicy: {
    MAX_TITLE_LENGTH: number; SHORT_MESSAGE_THRESHOLD: number
    buildTitlePrompt(message: string): string
    buildWindowTitlePrompt(sources: string[]): string
    collectTitleSources(messages: string[]): string[]
    mergeTitleRefineAttempts(current: number | undefined, candidate: number): number
    planTitleWindow(input: TitleWindowInput): TitleDecision
    preflightTitleWindow(input: Omit<TitleWindowInput, 'sourceCount'>): Exclude<TitleDecision, { action: 'generate' }> | null
    sanitizeGeneratedTitle(title: unknown): string | null
  }
}
